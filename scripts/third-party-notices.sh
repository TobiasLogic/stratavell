#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-THIRD_PARTY_NOTICES.md}
{
  echo "# Third-party notices"
  echo
  echo "Stratavell is licensed under the Apache License 2.0 (see LICENSE). Release binaries also contain the Go standard library and the modules below, each under its own license, reproduced here as their terms require."
  echo
  echo "This file is generated by scripts/third-party-notices.sh from the modules linked into cmd/stratavell and cmd/stratavell-bench."
  echo
  echo "## Go standard library"
  echo
  echo '```'
  cat "$(go env GOROOT)/LICENSE"
  echo '```'
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/stratavell ./cmd/stratavell-bench | sort -u | while read -r path version dir; do
    echo
    echo "## $path $version"
    for f in $(ls "$dir" | grep -i -E '^(license|licence|copying|notice)' | grep -v -i logo); do
      echo
      echo "### $f"
      echo
      echo '```'
      cat "$dir/$f"
      echo '```'
    done
  done
} > "$out"
echo "wrote $out"
